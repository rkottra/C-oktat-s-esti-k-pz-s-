CREATE DATABASE IF NOT EXISTS estis_oregfak
  CHARACTER SET utf8mb4 COLLATE utf8mb4_hungarian_ci;
USE estis_oregfak;

DROP TABLE IF EXISTS fa;
DROP TABLE IF EXISTS megye;

-- "1" oldal: egy vármegyében sok fa van
CREATE TABLE megye (
  id  INT NOT NULL AUTO_INCREMENT,
  nev VARCHAR(30) NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_hungarian_ci;

-- "N" oldal: minden fa pontosan egy vármegyéhez tartozik (megye_id idegen kulcs)
CREATE TABLE fa (
  id        INT NOT NULL AUTO_INCREMENT,
  faj       VARCHAR(50) NOT NULL,
  kormeret  INT NOT NULL COMMENT 'törzskerület cm-ben',
  telepules VARCHAR(50) NOT NULL,
  megye_id  INT NOT NULL,
  meres_eve INT NULL,
  PRIMARY KEY (id),
  KEY fk_fa_megye (megye_id),
  CONSTRAINT fk_fa_megye FOREIGN KEY (megye_id) REFERENCES megye (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_hungarian_ci;

